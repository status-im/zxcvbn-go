// Command gen turns the JSON frequency lists into constant dictionary tables:
// dictionaries_gen.go. Run it with go generate in internal/dictionary.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

// Must match endWidth and rankWidth in internal/dictionary/dictionary.go.
const (
	endWidth  = 3
	rankWidth = 2
)

// lists in the order the dictionary matchers run.
var lists = []struct{ name, file, ident string }{
	{"MaleNames", "MaleNames.json", "maleNames"},
	{"FemaleNames", "FemaleNames.json", "femaleNames"},
	{"Surname", "Surnames.json", "surname"},
	{"English", "English.json", "english"},
	{"Passwords", "Passwords.json", "passwords"},
}

func main() {
	var src bytes.Buffer
	src.WriteString("// Code generated by internal/dictionary/gen from lists/*.json; DO NOT EDIT.\n\npackage dictionary\n\n")

	var entries []string
	for _, l := range lists {
		words, ranks := rankedWords(filepath.Join("lists", l.file))
		var concat strings.Builder
		var ends, rankTable, firsts []byte
		for c := 0; c < 256; c++ {
			firsts = appendUint(firsts, sort.SearchStrings(words, string([]byte{byte(c)})), endWidth)
		}
		firsts = appendUint(firsts, len(words), endWidth)
		for k, w := range words {
			concat.WriteString(w)
			ends = appendUint(ends, concat.Len(), endWidth)
			rankTable = appendUint(rankTable, ranks[k], rankWidth)
		}
		fmt.Fprintf(&src, "const %sWords = %s\n\n", l.ident, strconv.Quote(concat.String()))
		fmt.Fprintf(&src, "const %sEnds = %s\n\n", l.ident, hexLiteral(ends))
		fmt.Fprintf(&src, "const %sRanks = %s\n\n", l.ident, hexLiteral(rankTable))
		fmt.Fprintf(&src, "const %sFirsts = %s\n\n", l.ident, hexLiteral(firsts))
		entries = append(entries, fmt.Sprintf("{Name: %q, words: %sWords, ends: %sEnds, ranks: %sRanks, firsts: %sFirsts},", l.name, l.ident, l.ident, l.ident, l.ident))
	}
	fmt.Fprintf(&src, "// All holds the ranked frequency lists, in the order the dictionary matchers run.\nvar All = [...]Dictionary{\n%s\n}\n", strings.Join(entries, "\n"))

	out, err := format.Source(src.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("dictionaries_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// rankedWords returns the lowercased words sorted bytewise, each with the rank the
// map-based dictionary gave it: index+1, the last occurrence winning on duplicates.
func rankedWords(path string) ([]string, []int) {
	raw, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	var list struct{ List []string }
	if err := json.Unmarshal(raw, &list); err != nil {
		log.Fatal(err)
	}

	rankOf := make(map[string]int, len(list.List))
	for i, w := range list.List {
		rankOf[strings.ToLower(w)] = i + 1
	}
	words := make([]string, 0, len(rankOf))
	for w := range rankOf {
		// Password substrings are compared bytewise, which matches the rune-based
		// lookup only for valid UTF-8 words.
		if w == "" || !utf8.ValidString(w) || strings.ContainsRune(w, utf8.RuneError) {
			log.Fatalf("%s: unsupported word %q", path, w)
		}
		words = append(words, w)
	}
	sort.Strings(words)

	ranks := make([]int, len(words))
	for k, w := range words {
		ranks[k] = rankOf[w]
	}
	return words, ranks
}

func appendUint(b []byte, v, width int) []byte {
	if v >= 1<<(8*width) {
		log.Fatalf("%d does not fit in %d bytes", v, width)
	}
	for i := 0; i < width; i++ {
		b = append(b, byte(v>>(8*i)))
	}
	return b
}

func hexLiteral(b []byte) string {
	var s strings.Builder
	s.Grow(2 + 4*len(b))
	s.WriteByte('"')
	for _, c := range b {
		fmt.Fprintf(&s, "\\x%02x", c)
	}
	s.WriteByte('"')
	return s.String()
}
